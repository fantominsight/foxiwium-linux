inline void draw_char(uint32_t x, uint32_t y, char c, Color color, int scale = 1) {
    uint8_t idx = (uint8_t)c;
    if (idx < 32 || idx > 127) idx = 32; // fallback to space
    const uint8_t* glyph = font_data[idx - 32];

    for (int row = 0; row < GLYPH_HEIGHT; row++) {
        uint8_t bits = glyph[row];
        for (int col = 0; col < GLYPH_WIDTH; col++) {
            if (bits & (0x80 >> col)) {
                for (int sy = 0; sy < scale; sy++) {
                    for (int sx = 0; sx < scale; sx++) {
                        graphics::put_pixel(
                            x + col * scale + sx,
                            y + row * scale + sy,
                            color
                        );
                    }
                }
            }
        }
    }
}

inline void draw_string(uint32_t x, uint32_t y, const char* str, Color color, int scale = 1) {
    uint32_t ox = x;
    while (*str) {
        if (*str == '\n') {
            x = ox;
            y += GLYPH_HEIGHT * scale + 2;
        } else {
            draw_char(x, y, *str, color, scale);
            x += GLYPH_WIDTH * scale;
        }
        str++;
    }
}

inline void draw_string_centered(uint32_t cx, uint32_t y, const char* str, Color color, int scale = 1) {
    int len = 0;
    const char* s = str;
    while (*s++) len++;
    uint32_t x = cx - (len * GLYPH_WIDTH * scale) / 2;
    draw_string(x, y, str, color, scale);
}

inline int text_width(const char* str, int scale = 1) {
    int len = 0;
    while (*str++) len++;
    return len * GLYPH_WIDTH * scale;
}

inline int text_height(int scale = 1) {
    return GLYPH_HEIGHT * scale;
}

